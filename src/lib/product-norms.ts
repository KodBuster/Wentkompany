/** Нормативные пояснения для карточки изделия; пусто — блок не показываем. */
export function productNormCards(family: string): NormCard[] {
  if (family === 'ГФ') return FILTER_CARDS;
  if (family === 'ЗВПГ' || family === 'ЗВОГ') return HOOD_HYDRO_CARDS;
  return [];
}

/** Статическая проверка: на ГФ не должно быть формулировок про встроенный гидрозатвор. */
export function assertGfNormsHaveNoBuiltInSealCopy(cards = productNormCards('ГФ')): void {
  const blob = cards.map((c) => c.text).join('\n').toLowerCase();
  for (const phrase of GF_FORBIDDEN_PHRASES) {
    if (blob.includes(phrase.toLowerCase())) {
      throw new Error(`Карточка ГФ содержит запрещённую формулировку: «${phrase}»`);
    }
  }
  const c531 = cards.find((c) => c.id === '5.31');
  if (!c531?.text.includes('5.11') || !c531.text.includes('ГОСТ Р 53321')) {
    throw new Error('п. 5.31 для ГФ должен ссылаться на п. 5.11 СП и ГОСТ Р 53321');
  }
  const c532 = cards.find((c) => c.id === '5.32');
  if (!c532?.text.includes('EI 45') || !c532.text.toLowerCase().includes('не допускается')) {
    throw new Error('п. 5.32 для ГФ должен упоминать EI 45 и запрет подключения');
  }
}
